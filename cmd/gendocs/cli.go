package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

// writeCLI writes one page per visible command, replacing the directory's
// pages so removed commands disappear.
func writeCLI(root *cobra.Command, dir string) error {
	if err := os.RemoveAll(dir); err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	order := 0
	var walk func(*cobra.Command) error
	walk = func(command *cobra.Command) error {
		if command.Hidden || command.Name() == "help" || command.Name() == "completion" {
			return nil
		}
		order++
		if err := os.WriteFile(filepath.Join(dir, pageName(command)+".md"), []byte(page(command, order)), 0o644); err != nil {
			return err
		}
		for _, child := range command.Commands() {
			if err := walk(child); err != nil {
				return err
			}
		}
		return nil
	}
	return walk(root)
}

func pageName(command *cobra.Command) string {
	return strings.ReplaceAll(command.CommandPath(), " ", "-")
}

func page(command *cobra.Command, order int) string {
	var b strings.Builder
	title := command.CommandPath()
	if command.Parent() == nil {
		title = "codeflower (overview)"
	}
	fmt.Fprintf(&b, "---\ntitle: %q\ndescription: %q\nsidebar:\n  order: %d\n  label: %q\n---\n\n",
		title, command.Short, order, sidebarLabel(command))
	b.WriteString("<!-- Generated by codeflower-app's cmd/gendocs: do not edit. -->\n\n")
	b.WriteString(prose(longOrShort(command)))

	b.WriteString("\n## Usage\n\n```sh\n" + command.UseLine() + "\n```\n")
	if len(command.Aliases) > 0 {
		fmt.Fprintf(&b, "\nAlso available as `%s %s`.\n", command.Parent().CommandPath(), strings.Join(command.Aliases, "`, `"))
	}
	if command.Example != "" {
		b.WriteString("\n## Examples\n\n```sh\n" + strings.TrimRight(command.Example, "\n") + "\n```\n")
	}
	if table := flagTable(command.NonInheritedFlags()); table != "" {
		b.WriteString("\n## Flags\n\n" + table)
	}
	if table := flagTable(command.InheritedFlags()); table != "" {
		b.WriteString("\n## Inherited flags\n\n" + table)
	}
	var children []string
	for _, child := range command.Commands() {
		if child.Hidden || child.Name() == "help" || child.Name() == "completion" {
			continue
		}
		children = append(children, fmt.Sprintf("- [`%s`](/reference/cli/%s/): %s", child.CommandPath(), pageName(child), child.Short))
	}
	if len(children) > 0 {
		b.WriteString("\n## Commands\n\n" + strings.Join(children, "\n") + "\n")
	}
	return b.String()
}

func sidebarLabel(command *cobra.Command) string {
	if command.Parent() == nil {
		return "Overview"
	}
	return strings.TrimPrefix(command.CommandPath(), "codeflower ")
}

func longOrShort(command *cobra.Command) string {
	if command.Long != "" {
		return command.Long
	}
	return command.Short
}

// prose turns help text into Markdown: paragraphs stay paragraphs, and
// indented blocks (examples in the help) become code blocks.
func prose(text string) string {
	var b strings.Builder
	for _, paragraph := range strings.Split(strings.TrimSpace(text), "\n\n") {
		lines := strings.Split(paragraph, "\n")
		indented := true
		for _, line := range lines {
			if !strings.HasPrefix(line, "  ") && !strings.HasPrefix(line, "\t") {
				indented = false
			}
		}
		if indented {
			b.WriteString("```sh\n" + dedent(lines) + "\n```\n\n")
			continue
		}
		b.WriteString(escape(strings.Join(lines, " ")) + "\n\n")
	}
	return b.String()
}

func dedent(lines []string) string {
	least := -1
	for _, line := range lines {
		if strings.TrimSpace(line) == "" {
			continue
		}
		indent := len(line) - len(strings.TrimLeft(line, " \t"))
		if least < 0 || indent < least {
			least = indent
		}
	}
	for i, line := range lines {
		if len(line) >= least {
			lines[i] = line[least:]
		}
	}
	return strings.Join(lines, "\n")
}

// escape keeps help text from being read as MDX: braces and angle brackets
// outside `code` are written as entities.
func escape(text string) string {
	var b strings.Builder
	inCode := false
	for _, r := range text {
		switch {
		case r == '`':
			inCode = !inCode
			b.WriteRune(r)
		case inCode:
			b.WriteRune(r)
		case r == '<':
			b.WriteString("&lt;")
		case r == '>':
			b.WriteString("&gt;")
		case r == '{':
			b.WriteString("&#123;")
		case r == '}':
			b.WriteString("&#125;")
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

func flagTable(flags *pflag.FlagSet) string {
	var rows []string
	flags.VisitAll(func(f *pflag.Flag) {
		if f.Hidden || f.Name == "help" {
			return
		}
		name, usage := pflag.UnquoteUsage(f)
		spelling := "--" + f.Name
		if f.Shorthand != "" {
			spelling = "-" + f.Shorthand + ", " + spelling
		}
		if name != "" {
			spelling += " " + name
		}
		rows = append(rows, fmt.Sprintf("| `%s` | %s | %s |", spelling, defaultValue(f), cell(usage)))
	})
	if len(rows) == 0 {
		return ""
	}
	return "| Flag | Default | Description |\n| --- | --- | --- |\n" + strings.Join(rows, "\n") + "\n"
}

func defaultValue(f *pflag.Flag) string {
	switch f.DefValue {
	case "", "false", "[]", "0", "0s":
		return ""
	}
	return "`" + f.DefValue + "`"
}

func cell(text string) string {
	return strings.ReplaceAll(escape(text), "|", "\\|")
}
